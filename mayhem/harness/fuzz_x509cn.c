int LLVMFuzzerTestOneInput(const uint8_t *Data, size_t Size)
{
#ifdef MBEDTLS_X509_CRT_PARSE_C
    mbedtls_x509_crt crt;
    uint32_t flags = 0;
    char *cn;

    mbedtls_x509_crt_init(&crt);
    if (psa_crypto_init() != PSA_SUCCESS) {
        goto exit;
    }
    if (mbedtls_x509_crt_parse_der(&crt, cert_der, sizeof(cert_der)) != 0) {
        goto exit;
    }

    cn = malloc(Size + 1);
    if (cn == NULL) {
        goto exit;
    }
    memcpy(cn, Data, Size);
    cn[Size] = '\0';

    (void) mbedtls_x509_crt_verify(&crt, NULL, NULL, cn, &flags, NULL, NULL);
    free(cn);

exit:
    mbedtls_x509_crt_free(&crt);
    mbedtls_psa_crypto_free();
#else
    (void) Data;
    (void) Size;
#endif
    return 0;
}
